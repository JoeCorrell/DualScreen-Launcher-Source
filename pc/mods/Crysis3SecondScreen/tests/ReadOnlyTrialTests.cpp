#include "../src/ReadOnlyTrial.h"
#include <cassert>
#include <iostream>
int main() {
    c3::Snapshot s{}; c3native::NativeActorValues actor{};
    actor.entity=7; actor.health=1000; actor.maxHealth=1000;
    actor.hasSuit=true; actor.energy=72; actor.maxEnergy=100; actor.mode=2;
    c3native::NativePhaseValues phase{}; phase.contextPresent=true; phase.contextReady=true;
    phase.environmentActive=true; phase.pauseKnown=true; phase.cutsceneKnown=true;
    c3::TrialVitals(s,actor,phase,true,8,1,1000);
    assert(c3::Current(s,1000) && !s.adapterVerified && s.readOnlyTrial && s.cloak.value);
    s.toggleCloak={1,c3::Action::ToggleCloak,true,true};
    assert(!c3::CanAct(s,s.toggleCloak,1000));
    assert(!c3::Current(s,1751));
    phase.paused=true;c3::TrialVitals(s,actor,phase,true,8,2,1001);
    assert(s.phase==c3::Phase::Paused && c3::Current(s,1001));
    phase.cutscene=true;c3::TrialVitals(s,actor,phase,true,8,3,1002);
    assert(!c3::Current(s,1002) && !s.health.known);
    phase.cutscene=false;phase.cutsceneKnown=false;c3::TrialVitals(s,actor,phase,true,8,4,1003);
    assert(!c3::Current(s,1003));
    phase.cutsceneKnown=true;c3::TrialVitals(s,actor,phase,false,9,5,1004);
    assert(!c3::Current(s,1004) && !s.health.known);
    c3::TrialVitals(s,actor,phase,true,10,6,1005);
    c3::research::RegularSingleObservation weapon{};weapon.entityId=3;weapon.loadedRounds=10;
    weapon.clipLimit=9;weapon.displayRounds=9;weapon.overflowRounds=1;weapon.ammoClass=123;
    std::snprintf(weapon.weaponClassName.data(),64,"Hammer");
    std::snprintf(weapon.ammoClassName.data(),64,"HPistolBullet");
    c3::TrialWeapon(s,weapon);
    assert(s.weapons.size()==1 && !s.weapons.complete && s.weapons.entries[0].magazine.value==10);
    assert(s.weapons.entries[0].capacity.value==9 && !s.weapons.entries[0].reserve.known);
    c3::research::AmmoObservation ammo{};ammo.found=true;ammo.count=48;ammo.capacity=54;ammo.ammoClass=123;
    c3::TrialInventoryAmmo(s,weapon,ammo);
    assert(s.resources.size()==1 && s.resources.entries[0].quantity.value==48 && !s.resources.complete);
    assert(!s.weapons.entries[0].reserve.known);
    c3::research::OwnedWeaponList names{}; names.count=2; names.currentItem=4;
    names.weapons[0].entityId=3; std::snprintf(names.weapons[0].className.data(),64,"Hammer");
    names.weapons[1].entityId=4; names.weapons[1].equipped=true;
    std::snprintf(names.weapons[1].className.data(),64,"NanoBow");
    c3::TrialOwnedWeapons(s,names);
    assert(s.weapons.size()==2 && s.weapons.complete && s.weapons.entries[0].name.str()=="Hammer");
    assert(s.weapons.entries[1].equipped.value && !s.weapons.entries[1].magazine.known);
    c3::TrialWeapon(s,weapon);
    assert(s.weapons.size()==2 && s.weapons.entries[1].name.str()=="NanoBow" && s.weapons.entries[0].magazine.value==10);
    names.count=6;
    for(size_t i=2;i<6;++i) names.weapons[i].entityId=uint32_t(10+i);
    std::snprintf(names.weapons[2].className.data(),64,"NoWeapon");
    std::snprintf(names.weapons[3].className.data(),64,"Binoculars");
    std::snprintf(names.weapons[4].className.data(),64,"PickAndThrowWeapon");
    std::snprintf(names.weapons[5].className.data(),64,"SCAR");
    c3::TrialOwnedWeapons(s,names);
    assert(s.weapons.size()==3 && s.weapons.entries[0].name.str()=="SCAR" && s.weapons.entries[1].name.str()=="Hammer");
    assert(s.weapons.entries[2].name.str()=="NanoBow");
    names.weapons[1].equipped=false; names.weapons[0].equipped=true;
    c3::TrialOwnedWeapons(s,names);
    assert(s.weapons.entries[1].name.str()=="Hammer" && s.weapons.entries[1].equipped.value);
    names.unavailable=1; c3::TrialOwnedWeapons(s,names); assert(!s.weapons.complete);
    c3native::NativeSuitModules modules{}; modules.count=2; modules.upgradePoints=4;
    std::snprintf(modules.modules[0].id.data(),32,"SuperStealth");
    std::snprintf(modules.modules[1].id.data(),32,"BulletProof"); modules.modules[1].installed=true;
    modules.modules[1].cost=3; modules.modules[1].unlockedKnown=false;
    c3::TrialSuitModules(s,modules);
    assert(s.modules.size()==2 && s.modules.entries[0].name.str()=="Deflection" && s.modules.entries[0].installed.value);
    assert(!s.modules.entries[0].purchased.value && !s.modules.entries[0].unlocked.known);
    assert(s.upgradePoints.known && s.upgradePoints.value==4 && !s.modules.entries[0].progress.known);
    c3::TrialSuitResource(s,modules);
    assert(s.resources.size()==2 && s.resources.entries[1].quantity.value==4 && !s.resources.entries[1].capacity.known);
    c3::Mailbox mailbox; assert(mailbox.RequestedPage()==c3::Page::Status);
    mailbox.RequestPage(c3::Page::Suit); mailbox.RequestPage(c3::Page::Count);
    assert(mailbox.RequestedPage()==c3::Page::Suit);
    c3::TrialVitals(s,actor,phase,true,11,7,1006);
    assert(!s.modules.known && !s.objectives.known && !s.resources.known && !s.weapons.known);
    std::cout<<"Read-only UI trial: phase/freshness/unknown fields and unconditional action rejection PASS\n";
}

// Passive access to Dead Island's native inventory, quest and skill menus.
//
// The bridge deliberately does not create a second gameplay model.  It copies
// text and selection state out of the game's already-populated XUI controls
// into owned C++ values, and resolves a control again before selecting it.
// Native pointers never escape this class and are discarded when ILevel
// changes.
//
// Actions invoke each derived control's real OnClickLB virtual through the
// slot derived from the exported base vtable. That is the same callback the
// native menu uses, so inventory ownership, quest tracking, skill costs,
// prerequisites and save persistence remain game-owned. The bridge never
// fabricates a controller/key event and never writes a gameplay field.

#pragma once

#include <cstddef>
#include <cstdint>
#include <string>
#include <vector>

#include "Engine.h"

namespace dis {

// A row copied from a native control.  Different XUI visuals expose different
// numbers of text fields, so preserving the ordered fields is safer than
// guessing that field 1 is always a quantity or a subtitle.
struct NativeUiRow {
  std::string id;
  // Engine texture identifier copied from the row's real I_Icon/I_Item
  // child. The custom renderer uses this as the semantic source for its
  // native-style glyph; it is never a fabricated inventory identity.
  std::string icon_texture;
  std::vector<std::string> text;
  // Exact EItemCategory value supplied by the direct gameplay bridge. Keeping
  // it separate from display text lets the inventory group weapons and parts
  // reliably in every language. Native-XUI fallback rows leave this at -1.
  int item_category = -1;
  bool selected = false;
  bool enabled = false;
  // A skill may be selectable for details while still being unavailable to
  // purchase. Native XUI used one enabled bit for both concepts; the direct
  // gameplay bridge keeps them separate so locked branches remain readable.
  bool purchasable = false;
  int group = -1;  // skill tree for skill rows; otherwise -1
  int tier = -1;   // skill tier for skill rows; otherwise -1
  // Local coordinates authored by the native XUI controller. Skill nodes in
  // the same tier use different X positions to describe a branch; retaining
  // them prevents the companion page from flattening every tree into a list.
  float native_x = 0.0f;
  float native_y = 0.0f;
  bool has_native_position = false;
  // Structural ordinal inside the native list/tier. Display text is not a
  // stable identity: several skill buttons legitimately contain the same
  // rank string (for example, "0/3"). Keeping the authored/runtime ordinal
  // lets a later action reacquire the exact control without collapsing
  // siblings that happen to share their text.
  int native_ordinal = -1;
};

struct InventorySnapshot {
  bool available = false;
  std::string unavailable_reason;
  std::string selected_name;
  std::string description;
  std::string price;
  std::string filter;
  std::vector<NativeUiRow> items;
  bool equip_control_enabled = false;
  bool drop_control_enabled = false;
  bool compare_control_enabled = false;
  bool inspect_control_enabled = false;
};

struct GearSnapshot {
  bool available = false;
  std::string unavailable_reason;
  std::vector<NativeUiRow> quick_slots;
};

struct MissionsSnapshot {
  bool available = false;
  std::string unavailable_reason;
  std::string selected_name;
  std::string reward;
  std::string description;
  std::vector<NativeUiRow> quests;
  std::vector<NativeUiRow> objectives;
  bool track_control_enabled = false;
  bool details_control_enabled = false;
};

struct SkillsSnapshot {
  bool available = false;
  std::string unavailable_reason;
  std::string available_points;
  std::string selected_name;
  std::string selected_level;
  std::string description;
  std::vector<NativeUiRow> skills;
  bool learn_control_enabled = false;
  bool view_control_enabled = false;
  bool reskill_control_enabled = false;
  bool confirmation_visible = false;
};

// Owned projection of the live vanilla HudRadar tree. Runtime path and marker
// controls are generated by the game's own navigation/objective controller;
// copying their final local bounds preserves its route calculation without
// retaining game-owned UI pointers or inventing a second navigation model.
struct HudRadarVisual {
  float x = 0.0f;
  float y = 0.0f;
  float width = 0.0f;
  float height = 0.0f;
  float scale_x = 1.0f;
  float scale_y = 1.0f;
  std::string texture;
  std::string label;
  bool up = false;
};

struct HudRadarSnapshot {
  bool available = false;
  HudRadarVisual player;
  std::vector<HudRadarVisual> path;
  std::vector<HudRadarVisual> markers;
};

// Always-live text exposed by the gameplay HUD. Screen 1024 stays logically
// visible while the custom UI suppresses only its opacity, so these values do
// not inherit the hidden-menu lifetime problem of Inventory/Skills.
struct HudSnapshot {
  bool available = false;
  std::string equipped_name;
  std::string icon_texture;
  // Current/next-level XP text copied from HudPlayer's live XP presenter.
  std::string xp;
  std::string clip_ammo;
  std::string total_ammo;
  std::string held_quantity;
  std::string durability;
  std::vector<std::string> item_stats;
  HudRadarSnapshot radar;
};

enum class InventoryNativeAction {
  kEquip,
  kDrop,
  kCompare,
  kInspect,
  kCollectableDetails,
  kFilter,
  kBack,
};

enum class MissionNativeAction {
  kTrack,
  kDetails,
  kBack,
};

enum class SkillNativeAction {
  kLearn,
  kView,
  kReskill,
  kBack,
  kConfirmYes,
  kConfirmNo,
  kConfirmOk,
};

enum class NativeUiDomain {
  kAll,
  kInventory,
  kMissions,
  kSkills,
};

// gamedll registers gameplay-authored menus on its UI host, which is not the
// playable-world ILevel selected for player/world state. The narrow
// RegisterUIScreen IAT observer publishes that proven host here; all native
// menu operations then use it while HUD/world operations continue using the
// main ILevel.
void ObserveNativeMenuRegistration(ILevel* host, int screen_id,
                                   const char* script_name);
void RetireNativeMenuHost(ILevel* host);

class NativeUi {
 public:
#ifdef DIS_UI_PREVIEW
  void SetPreviewData();
#endif
  // Must run on the same game/render thread used for the other Engine calls.
  // Update is bounded. It advances only a menu activation explicitly requested
  // through SetInteractiveDomain; otherwise the fallback XUI adapter reads a
  // controller the game already has visible. Hidden controllers are rejected.
  void Update(ILevel* level, NativeUiDomain domain = NativeUiDomain::kAll);
  void UpdateHud(ILevel* level);
  // Makes the real game controller backing a custom interactive page live,
  // while holding its authored root at zero opacity behind the custom panel.
  // Passing kAll schedules any companion controller to close after its pending
  // Show has produced one safe snapshot. Must run on the game thread.
  bool SetInteractiveDomain(ILevel* level, NativeUiDomain domain);
  void Reset();

  uint64_t revision() const { return revision_; }
  uint64_t inventory_revision() const { return inventory_revision_; }
  uint64_t missions_revision() const { return missions_revision_; }
  uint64_t skills_revision() const { return skills_revision_; }
  const InventorySnapshot& inventory() const { return inventory_; }
  const GearSnapshot& gear() const { return gear_; }
  const MissionsSnapshot& missions() const { return missions_; }
  const SkillsSnapshot& skills() const { return skills_; }
  const HudSnapshot& hud() const { return hud_; }

  // Selection is semantic and index-based.  The native screen and row are
  // reacquired for every call, so no pointer from a previous frame is used.
  // These return false if the screen was unloaded, the row disappeared, or
  // the native control is disabled.
  bool SelectInventoryItem(std::size_t index);
  bool AssignInventoryItemToQuickSlot(std::size_t inventory_index,
                                      std::size_t quick_slot);
  bool SelectGearSlot(std::size_t index);
  // One-shot gameplay hotbar action for the always-visible Stats page. It
  // opens the real inventory controller at zero opacity, waits for its native
  // data associations on later UI ticks, invokes B_SlotN, then restores the
  // previous gameplay view.
  bool ActivateQuickSlot(std::size_t index);
  bool SelectMission(std::size_t index);
  bool SelectSkill(std::size_t index);

  // Invokes the corresponding native action control.
  bool SelectInventoryAction(InventoryNativeAction action);
  bool SelectMissionAction(MissionNativeAction action);
 bool SelectSkillAction(SkillNativeAction action);

 private:
  // ShowUIScreen is allowed to complete on a later UI tick. These helpers keep
  // the requested controller alive and transparent until the engine reports
  // it ready, then close it through the normal native path. They are called
  // only on the game/render thread.
  bool AdvanceInteractive(ILevel* level);
  void CloseInteractive(ILevel* level);

  ILevel* level_ = nullptr;
  uint64_t revision_ = 0;
  uint64_t inventory_revision_ = 0;
  uint64_t missions_revision_ = 0;
  uint64_t skills_revision_ = 0;
  std::string fingerprint_;
  InventorySnapshot inventory_;
  GearSnapshot gear_;
  MissionsSnapshot missions_;
  SkillsSnapshot skills_;
  HudSnapshot hud_;
  std::string hud_fingerprint_;
  int interactive_screen_id_ = -1;
  NativeUiDomain interactive_domain_ = NativeUiDomain::kAll;
  bool interactive_ready_ = false;
  bool close_when_ready_ = false;
  int activation_polls_ = 0;
  int pending_quick_slot_ = -1;
  bool pending_quick_slot_wait_ = false;
};

NativeUi& TheNativeUi();

}  // namespace dis

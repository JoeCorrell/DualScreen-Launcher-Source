"""Read-only verification of power images against the original Flash symbols.

Input is FFDec's swf2xml export of UI_Journal_SF.gfx. Frame labels and shape
bitmap references establish icon identity; visual resemblance is insufficient.
No images, staging directories or payloads are generated by this tool.
"""
import argparse
import hashlib
import json
from pathlib import Path
import xml.etree.ElementTree as ET

from prepare_assets import IMAGES

POWERS = {
    "shadow_kill": ("power-shadow-kill", "Journal_I78.tga"),
    "blood_thirst": ("power-blood-thirsty", "Journal_I7A.tga"),
    "celerity": ("power-agility", "Journal_I7C.tga"),
    "vitality": ("power-vitality", "Journal_I7E.tga"),
    "dark_vision": ("power-dark-vision", "Journal_I80.tga"),
    "wind_blast": ("power-windblast", "Journal_I82.tga"),
    "rat_swarm": ("power-devouring-swarm", "Journal_I84.tga"),
    "blink": ("power-blink", "Journal_I86.tga"),
    "bend_time": ("power-bend-time", "Journal_I88.tga"),
    "possession": ("power-possession", "Journal_I8A.tga"),
}


def verify(path):
    if not 0 < path.stat().st_size <= 16 * 1024 * 1024:
        raise ValueError("Unexpected Flash metadata size")
    data = path.read_bytes()
    root = ET.fromstring(data)
    tags = root.findall("./tags/item")
    images = {int(x.attrib["characterID"]): x.attrib["fileName"]
              for x in tags if x.attrib.get("type") == "DefineExternalImage2"}
    shapes = {int(x.attrib["shapeId"]): [int(y.attrib["bitmapId"]) for y in x.iter() if "bitmapId" in y.attrib]
              for x in tags if "shapeId" in x.attrib}
    sprite = next(x for x in tags if x.attrib.get("spriteId") == "140")
    label = None
    observed = {}
    for tag in sprite.find("subTags"):
        kind = tag.attrib.get("type", "")
        if kind == "FrameLabelTag":
            label = tag.attrib["name"]
        elif label and kind.startswith("PlaceObject") and "characterId" in tag.attrib:
            character = int(tag.attrib["characterId"])
            observed[label] = [images.get(bitmap) for bitmap in shapes.get(character, [])]
            label = None
    for label, (role, export) in POWERS.items():
        if observed.get(label) != [export] or IMAGES[role] + ".tga" != export:
            raise ValueError("Original symbol/artwork mapping mismatch: " + label)
    return {"scope": "Original Flash symbol metadata; no rendering or game execution",
            "metadataSha256": hashlib.sha256(data).hexdigest(), "sprite": 140,
            "verified": {label: files[0] for label, files in observed.items() if label in POWERS}}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("xml", type=Path)
    parser.add_argument("--report", type=Path)
    args = parser.parse_args()
    result = verify(args.xml)
    if args.report:
        args.report.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    print("Verified all ten original power icon mappings. No build or resource staging.")

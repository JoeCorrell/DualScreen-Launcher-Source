int FillSnapshot(EmulationSession& session, void* output, std::size_t output_size) {
    if (!output || output_size < sizeof(SnapshotFrame)) {
        return -1;
    }

    SnapshotFrame frame{};
    frame.magic = 0x44485353; // "SSHD" in a little-endian direct buffer.
    frame.version = 5;
    frame.size = sizeof(frame);
    frame.sequence = Sequence.fetch_add(1, std::memory_order_relaxed) + 1;
    frame.status = static_cast<u32>(Status::NotRunning);
    frame.summary_message_id = 0xFFFF;
    frame.objective_message_id = 0xFFFF;
    frame.equipped_b_item = 0xFF;
    frame.selected_pouch_slot = 0xFF;
    frame.shield_pouch_slot = 0xFF;
    frame.selected_dowsing_slot = 0xFF;
    frame.current_room = 0xFF;
    frame.current_layer = 0xFF;
    frame.current_entrance = 0xFF;
    frame.current_trial = 0xFF;
    frame.current_scene_index = InvalidSceneIndex;
    frame.current_dungeon_index = InvalidSceneIndex;
    frame.player_room = 0xFF;
    frame.player_action = 0xFFFFFFFFU;
    frame.map_title_id = -1;
    frame.stif_area = 0xFF;
    frame.stif_field = 0xFF;
    frame.stif_room_type = 0xFF;
    frame.link_outfit = 0xFF;
    frame.current_map_mode = -1;
    frame.next_map_mode = -1;
    frame.map_floor = InvalidMapFloor;
    frame.player_heading_radians = std::numeric_limits<float>::quiet_NaN();
    std::fill(std::begin(frame.pouch_items), std::end(frame.pouch_items), -1);
    std::fill(std::begin(frame.item_check_items), std::end(frame.item_check_items), -1);

    [[maybe_unused]] auto system_access = session.LockSystemAccess();
    if (!session.IsRunning()) {
        InvalidateLifecycleIdentity();
        LogRuntimeStatus(Status::NotRunning, 0, 0, 0, 0, 0, 0);
        std::memcpy(output, &frame, sizeof(frame));
        return sizeof(frame);
    }
    auto& system = session.System();
    if (system.GetApplicationProcessProgramID() != TitleId) {
        InvalidateLifecycleIdentity();
        frame.status = static_cast<u32>(Status::WrongTitle);
        LogRuntimeStatus(Status::WrongTitle, 1, 0, 0, 0, 0, 0);
        std::memcpy(output, &frame, sizeof(frame));
        return sizeof(frame);
    }
    if (system.GetApplicationProcessBuildID() != BuildId) {
        InvalidateLifecycleIdentity();
        frame.status = static_cast<u32>(Status::UnsupportedBuild);
        LogRuntimeStatus(Status::UnsupportedBuild, 2, 0, 0, 0, 0, 0);
        std::memcpy(output, &frame, sizeof(frame));
        return sizeof(frame);
    }

    const auto [main_base, main_size] = system.GetApplicationProcessMainModule();
    if (!main_base || main_size < RequiredMainSize) {
        InvalidateLifecycleIdentity();
        frame.status = static_cast<u32>(Status::Loading);
        frame.capabilities = 3U << 24;
        LogRuntimeStatus(Status::Loading, 3, main_base, main_size, 0, 0, 0);
        std::memcpy(output, &frame, sizeof(frame));
        return sizeof(frame);
    }
    auto& memory = system.ApplicationMemory();

    // Resolve the authoritative state directly from the exact-build globals.
    // Do not fall back to the game-thread mailbox here: it may be stale across
    // transitions and its callback is not guaranteed to run under NCE.
    const VAddr direct_file_manager =
        Read<u64>(memory, main_base + FileManagerPointerOffset).value_or(0);
    const VAddr file_manager = SelectReadablePointer(
        memory, direct_file_manager, 0, FileManagerSaveAOffset + SaveFileSize);
    const VAddr save = file_manager ? file_manager + FileManagerSaveAOffset : 0;
    const VAddr direct_player = Read<u64>(memory, main_base + PlayerPointerOffset).value_or(0);
    const VAddr player = SelectReadablePointer(
        memory, direct_player, 0, PlayerStaminaOffset + sizeof(u32));
    const VAddr direct_story_flag_manager =
        Read<u64>(memory, main_base + StoryFlagManagerPointerOffset).value_or(0);
    const VAddr story_flag_manager =
        SelectReadablePointer(memory, direct_story_flag_manager, 0, 32);
    const VAddr direct_item_flag_manager =
        Read<u64>(memory, main_base + ItemFlagManagerPointerOffset).value_or(0);
    const VAddr item_flag_manager =
        SelectReadablePointer(memory, direct_item_flag_manager, 0, 32);

    if (!file_manager || !IsReadableRange(memory, save, SaveFileSize)) {
        InvalidateLifecycleIdentity();
        frame.status = static_cast<u32>(Status::Loading);
        frame.capabilities = 4U << 24;
        LogRuntimeStatus(Status::Loading, 4, main_base, main_size, file_manager, 0, 0);
        std::memcpy(output, &frame, sizeof(frame));
        return sizeof(frame);
    }

    const bool stage_read = ReadBytes(memory, main_base + CurrentStageOffset, frame.stage_name,
                                      sizeof(frame.stage_name));
    const auto capacity = Read<u16>(memory, save + SaveHealthCapacityOffset);
    const auto health = Read<u16>(memory, save + SaveCurrentHealthOffset);
    std::array<s32, 8> live_pouch_items{};
    const bool pouch_read =
        ReadBytes(memory, save + SavePouchOffset, live_pouch_items.data(),
                  sizeof(live_pouch_items));
    u32 effective_capacity = capacity.value_or(0);
    if (pouch_read) {
        const auto life_medals = std::count_if(
            live_pouch_items.begin(), live_pouch_items.end(), [](s32 packed) {
                return packed >= 0 && static_cast<u8>(packed & 0xFF) == ItemLifeMedal;
            });
        effective_capacity +=
            static_cast<u32>(life_medals) * LifeMedalHealthBonus;
    }
    if (!stage_read || !HasPlayableStageName(frame.stage_name, sizeof(frame.stage_name)) ||
        !player || !capacity || !health || *capacity == 0 ||
        *capacity > MaxBaseHealthCapacity ||
        effective_capacity > MaxEffectiveHealthCapacity ||
        *health > MaxEffectiveHealthCapacity ||
        (pouch_read && *health > effective_capacity)) {
        InvalidateLifecycleIdentity();
        frame.status = static_cast<u32>(Status::Loading);
        frame.capabilities = 5U << 24;
        LogRuntimeStatus(Status::Loading, 5, main_base, main_size, file_manager,
                         static_cast<u16>(effective_capacity), health.value_or(0));
        std::memcpy(output, &frame, sizeof(frame));
        return sizeof(frame);
    }

    frame.current_health = *health;
    frame.health_capacity = static_cast<u16>(effective_capacity);
    if (!pouch_read ||
        !ReadBytes(memory, save + SaveItemCheckOffset, frame.item_check_items,
                   sizeof(frame.item_check_items)) ||
        !ReadBytes(memory, save + SavePotionTimersOffset, frame.potion_timers,
                   sizeof(frame.potion_timers)) ||
        !ReadBytes(memory, save + SaveAreaOffset, frame.area_name, sizeof(frame.area_name))) {
        InvalidateLifecycleIdentity();
        frame.status = static_cast<u32>(Status::Loading);
        frame.capabilities = 6U << 24;
        LogRuntimeStatus(Status::Loading, 6, main_base, main_size, file_manager, *capacity,
                         *health);
        std::memcpy(output, &frame, sizeof(frame));
        return sizeof(frame);
    }
    std::copy(live_pouch_items.begin(), live_pouch_items.end(), std::begin(frame.pouch_items));
    frame.equipped_b_item = Read<u8>(memory, save + SaveEquippedBItemOffset).value_or(0xFF);
    frame.selected_pouch_slot = Read<u8>(memory, save + SaveSelectedPouchOffset).value_or(0xFF);
    frame.shield_pouch_slot = Read<u8>(memory, save + SaveShieldPouchOffset).value_or(0xFF);
    frame.selected_dowsing_slot = Read<u8>(memory, save + SaveDowsingOffset).value_or(0xFF);
    frame.current_room = Read<u8>(memory, main_base + CurrentStageOffset + CurrentRoomOffset)
                             .value_or(0xFF);
    frame.current_layer = Read<u8>(memory, main_base + CurrentStageOffset + CurrentLayerOffset)
                              .value_or(0xFF);
    frame.current_entrance =
        Read<u8>(memory, main_base + CurrentStageOffset + CurrentEntranceOffset)
            .value_or(0xFF);
    frame.current_night = Read<u8>(memory, main_base + CurrentStageOffset + CurrentNightOffset)
                              .value_or(0);
    frame.current_trial = Read<u8>(memory, main_base + CurrentStageOffset + CurrentTrialOffset)
                              .value_or(0);
    frame.new_file = Read<u8>(memory, save + SaveNewFileOffset).value_or(0);
    SanitizeAscii(frame.stage_name, sizeof(frame.stage_name));
    SanitizeAscii(frame.area_name, sizeof(frame.area_name));
    frame.capabilities |= SaveState;

    if (player) {
        const auto stamina =
            Read<u32>(memory, ResolveStaminaAddress(player, frame.stage_name));
        if (stamina && *stamina <= FullStaminaAmount) {
            frame.stamina_amount = *stamina;
            frame.capabilities |= PlayerState;
        }

        std::array<float, 3> position{};
        const auto yaw = Read<s16>(memory, player + PlayerRotationOffset + sizeof(s16));
        const auto action = Read<u32>(memory, player + PlayerActionOffset);
        if (ReadBytes(memory, player + PlayerPositionOffset, position.data(), sizeof(position)) &&
            IsSanePosition(position) && yaw) {
            std::copy(position.begin(), position.end(), std::begin(frame.player_position));
            frame.player_yaw_radians = static_cast<float>(*yaw) * AngleToRadians;
            frame.player_room = Read<u8>(memory, player + PlayerRoomOffset).value_or(0xFF);
            frame.capabilities |= PlayerTransformState;
        }
        if (action && *action <= 0x1000) {
            frame.player_action = *action;
        }

        // Exact 1.0.1 player+0x1A2B is the model loader's mTunicType byte.
        // Normalize the game's enum to the two preview assets requested by the
        // companion ABI: 0 opening pl_*, 1 green al*. Silent/invalid models do
        // not claim an appearance capability.
        const auto tunic_type = Read<u8>(memory, player + PlayerTunicTypeOffset);
        if (tunic_type && *tunic_type == 1) {
            frame.link_outfit = 0;
            frame.capabilities |= LinkAppearanceState;
        } else if (tunic_type && *tunic_type == 0) {
            frame.link_outfit = 1;
            frame.capabilities |= LinkAppearanceState;
        }
    }

    ReadMapState(memory, main_base, frame);
    if (HasReadyMapImage(memory, main_base,
                         system.GetApplicationProcessCompanionMailbox())) {
        frame.capabilities |= MapImageState;
    }

    const VAddr scene_flag_manager = SelectReadablePointer(
        memory, Read<u64>(memory, main_base + SceneFlagManagerPointerOffset).value_or(0), 0,
        SceneFlagIndexOffset + sizeof(u16));
    const VAddr dungeon_flag_manager = SelectReadablePointer(
        memory, Read<u64>(memory, main_base + DungeonFlagManagerPointerOffset).value_or(0), 0,
        DungeonFlagSpaceOffset + FlagSpaceCountOffset + sizeof(u16));
    const auto saved_scene_index = Read<s16>(memory, save + SaveSceneIndexOffset);

    if (scene_flag_manager) {
        const auto scene_index = Read<u16>(memory, scene_flag_manager + SceneFlagIndexOffset);
        if (scene_index && *scene_index < 26) {
            frame.current_scene_index = static_cast<s16>(*scene_index);
        }
        if (const auto row = ReadFlagRow(memory, scene_flag_manager + SceneFlagSpaceOffset)) {
            std::copy(row->begin(), row->end(), std::begin(frame.current_scene_flags));
            frame.capabilities |= SceneFlagState;
        }
    }
    if (frame.current_scene_index == InvalidSceneIndex && saved_scene_index &&
        *saved_scene_index >= 0 && *saved_scene_index < 26) {
        frame.current_scene_index = *saved_scene_index;
    }
    if (!(frame.capabilities & SceneFlagState) &&
        frame.current_scene_index != InvalidSceneIndex &&
        ReadBytes(memory,
                  save + SaveSceneFlagsOffset +
                      static_cast<VAddr>(frame.current_scene_index) * CurrentFlagRowCount *
                          sizeof(u16),
                  frame.current_scene_flags, sizeof(frame.current_scene_flags))) {
        frame.capabilities |= SceneFlagState;
    }

    if (dungeon_flag_manager) {
        const auto dungeon_index = Read<u8>(memory, dungeon_flag_manager + DungeonFlagIndexOffset);
        if (dungeon_index && *dungeon_index < 26) {
            frame.current_dungeon_index = static_cast<s16>(*dungeon_index);
        }
        if (const auto row = ReadFlagRow(memory, dungeon_flag_manager + DungeonFlagSpaceOffset)) {
            std::copy(row->begin(), row->end(), std::begin(frame.current_dungeon_flags));
            frame.capabilities |= DungeonFlagState;
        }
    }
    if (frame.current_dungeon_index == InvalidSceneIndex && saved_scene_index &&
        *saved_scene_index >= 0 && *saved_scene_index < 26) {
        frame.current_dungeon_index = *saved_scene_index;
    }
    if (!(frame.capabilities & DungeonFlagState) &&
        frame.current_dungeon_index != InvalidSceneIndex &&
        ReadBytes(memory,
                  save + SaveDungeonFlagsOffset +
                      static_cast<VAddr>(frame.current_dungeon_index) * CurrentFlagRowCount *
                          sizeof(u16),
                  frame.current_dungeon_flags, sizeof(frame.current_dungeon_flags))) {
        frame.capabilities |= DungeonFlagState;
    }

    const u64 save_time = Read<u64>(memory, save + SaveTimeOffset).value_or(0);
    frame.lifecycle_epoch =
        UpdateLifecycleEpoch(file_manager, player, frame.stage_name, frame.current_room,
                             frame.current_layer, frame.current_scene_index,
                             frame.current_dungeon_index, save_time, frame.new_file != 0,
                             frame.current_health == 0);
    frame.capabilities |= LifecycleState;

    const auto item_flags =
        ResolveFlagReader(memory, item_flag_manager, 0x40, ItemDefinitionCount);
    const auto story_flags =
        ResolveFlagReader(memory, story_flag_manager, 0x80, StoryDefinitionCount);
    if (item_flags) {
        for (u16 id = 0; id <= MaxDirectItemId; ++id) {
            frame.item_values[id] = item_flags->Get(id).value_or(0);
        }
        for (const auto& mapping : InsectCounterMappings) {
            frame.item_values[mapping.item_id] =
                item_flags->Get(mapping.counter_flag).value_or(0);
        }
        for (const auto& mapping : MaterialCounterMappings) {
            frame.item_values[mapping.item_id] =
                item_flags->Get(mapping.counter_flag).value_or(0);
        }
        frame.heart_pieces = item_flags->Get(0x1E9).value_or(0);
        frame.pouch_expansions = item_flags->Get(0x1EA).value_or(0);
        frame.seeds = item_flags->Get(0x1ED).value_or(0);
        frame.arrows = item_flags->Get(0x1F2).value_or(0);
        frame.bombs = item_flags->Get(0x1F3).value_or(0);
        frame.rupees = item_flags->Get(0x1F5).value_or(0);
        frame.gratitude_crystals = item_flags->Get(0x1F6).value_or(0);
        frame.key_pieces = item_flags->Get(0x1F9).value_or(0);
        frame.extra_wallets = item_flags->Get(0x1FC).value_or(0);
        // Gratitude Crystal ITEM_1_CRYSTAL uses its acquisition flag for
        // discovery but the pause count comes from the dedicated counter.
        frame.item_values[48] = frame.gratitude_crystals;
        frame.item_values[199] = frame.extra_wallets;
        frame.capabilities |= FlagState;

        // The exact 1.0.1 dAcItem::checkFlag table maps ordinary companion
        // inventory entries directly to item flags. Preserve those raw values
        // before the quantity remaps above split discovery from current count.
        for (u16 id = 0; id <= MaxDirectItemId; ++id) {
            SetItemOwned(frame, id, item_flags->Get(id).value_or(0) != 0);
        }

        if (story_flags) {
            // Original pause visibility has two non-item-flag families: Deku
            // Hornet is story flag 122 and material discoveries are story
            // flags 753..768. These remain set after the count reaches zero.
            SetItemOwned(frame, 143,
                         story_flags->Get(StoryDekuHornetCollected).value_or(0) != 0);
            for (std::size_t i = 0; i < MaterialCounterMappings.size(); ++i) {
                SetItemOwned(
                    frame, MaterialCounterMappings[i].item_id,
                    story_flags->Get(static_cast<u16>(StoryFirstMaterialCollected + i))
                            .value_or(0) != 0);
            }
        }

        // These two ITEM_* values have no persistent dAcItem ownership flag:
        // Sacred Water is bottle content, while Extra Wallet is a counter.
        const bool has_sacred_water =
            std::any_of(std::begin(frame.pouch_items), std::end(frame.pouch_items),
                        [](s32 packed) { return packed >= 0 && (packed & 0xFF) == 74; });
        SetItemOwned(frame, 74, has_sacred_water);
        SetItemOwned(frame, 199, frame.extra_wallets != 0);
        frame.capabilities |= ItemOwnershipState;
    }
    if (story_flags) {
        if (story_flags->Get(StoryBossRushActive).value_or(0) != 0) {
            frame.summary_message_id = 40;
            frame.objective_message_id = 92;
        } else {
            frame.summary_message_id = FindProgressMessage(*story_flags, SummaryEntries);
            const bool imprisoned_repeat =
                story_flags->Get(StoryImprisonedFight).value_or(0) != 0 &&
                story_flags->Get(StoryImprisonedOneFight).value_or(0) != 0 &&
                story_flags->Get(StoryImprisonedTwoFight).value_or(0) != 0 &&
                story_flags->Get(StoryImprisonedThreeFight).value_or(0) != 0 &&
                story_flags->Get(StoryImprisonedThreeDefeated).value_or(0) == 0;
            if (imprisoned_repeat) {
                frame.objective_message_id = 70;
            } else if (story_flags->Get(StoryThunderDragonSongComplete).value_or(0) == 0 &&
                       item_flags && item_flags->Get(ItemLifeTreeSeedling).value_or(0) != 0 &&
                       item_flags->Get(ItemLifeTreeFruit).value_or(0) == 0) {
                frame.objective_message_id = 90;
            } else if (story_flags->Get(StoryThunderDragonSongComplete).value_or(0) == 0 &&
                       item_flags && item_flags->Get(ItemLifeTreeFruit).value_or(0) != 0) {
                frame.objective_message_id = 91;
            } else {
                frame.objective_message_id = FindProgressMessage(*story_flags, ObjectiveEntries);
            }
        }
        for (const auto& entry : SummaryEntries) {
            if (entry.message_id == frame.summary_message_id ||
                story_flags->Get(entry.story_flag).value_or(0) == 0 ||
                frame.completed_summary_count >= ProgressHistoryCount) {
                continue;
            }
            frame.completed_summary_message_ids[frame.completed_summary_count++] =
                entry.message_id;
        }
        frame.capabilities |= ProgressState;
        frame.capabilities |= ProgressHistoryState;
    }

    frame.status = static_cast<u32>(Status::Active);
    LogRuntimeStatus(Status::Active, 7, main_base, main_size, file_manager,
                     frame.health_capacity, *health);
    std::memcpy(output, &frame, sizeof(frame));
    return sizeof(frame);
}

int CopyMapImage(EmulationSession& session, void* output, std::size_t output_size) {
    using Payload = Loader::SshdCompanionPayload::Mailbox;
    using CaptureState = Loader::SshdCompanionPayload::MapCaptureState;
    using CaptureResult = Loader::SshdCompanionPayload::MapCaptureResult;

    if (!output || output_size < sizeof(MapImageHeaderV1)) {
        return -1;
    }

    Payload capture{};
    std::vector<u8> tiled;
    {
        [[maybe_unused]] auto system_access = session.LockSystemAccess();
        if (!session.IsRunning()) {
            return -2;
        }
        auto& system = session.System();
        if (system.GetApplicationProcessProgramID() != TitleId ||
            system.GetApplicationProcessBuildID() != BuildId) {
            return -2;
        }
        const auto [main_base, main_size] = system.GetApplicationProcessMainModule();
        const VAddr mailbox_address = system.GetApplicationProcessCompanionMailbox();
        if (!main_base || main_size < RequiredMainSize || !mailbox_address) {
            return -3;
        }
        auto& memory = system.ApplicationMemory();
        const auto payload = ReadMapCaptureMailbox(memory, mailbox_address);
        if (!payload) {
            // The bridge initializes its exact-version header on the guest
            // game thread. Do not write into an unrecognized mailbox.
            constexpr u64 InvalidMailboxSignature = 0xFFFFFFFFFFFFFFFEULL;
            if (LoggedMapCaptureSignature.exchange(InvalidMailboxSignature,
                                                   std::memory_order_relaxed) !=
                InvalidMailboxSignature) {
                LOG_INFO(Frontend, "[SSHD-MAP] waiting for capture-hook mailbox initialization");
            }
            return -3;
        }

        const u64 capture_signature =
            static_cast<u64>(payload->map_state) |
            (static_cast<u64>(payload->map_result) << 4) |
            (static_cast<u64>(payload->map_request) << 8) |
            (static_cast<u64>(payload->map_in_flight) << 24) |
            (static_cast<u64>(payload->map_completed) << 40) |
            (static_cast<u64>(payload->map_format) << 56);
        if (LoggedMapCaptureSignature.exchange(capture_signature,
                                               std::memory_order_relaxed) !=
            capture_signature) {
            LOG_INFO(Frontend,
                     "[SSHD-MAP] state={} result={} request={} in_flight={} completed={} "
                     "ack={} stage={:#x} texture={:#x} data={:#x} size={}x{} format={} floor={}",
                     payload->map_state, payload->map_result, payload->map_request,
                     payload->map_in_flight, payload->map_completed,
                     payload->map_acknowledged, payload->map_stage,
                     payload->map_texture, payload->map_data, payload->map_width,
                     payload->map_height, payload->map_format, payload->map_floor);
        }

        const auto state = static_cast<CaptureState>(payload->map_state);
        if (state == CaptureState::Rejected) {
            Write(memory, mailbox_address + offsetof(Payload, map_acknowledged),
                  payload->map_completed);
            return payload->map_result == static_cast<u32>(CaptureResult::NoStage) ? -2 : -5;
        }
        if (state == CaptureState::Idle) {
            if (payload->map_request == payload->map_completed) {
                u32 request = MapRequestSequence.fetch_add(1, std::memory_order_relaxed) + 1;
                if (request == 0) {
                    request = MapRequestSequence.fetch_add(1, std::memory_order_relaxed) + 1;
                }
                if (!Write(memory, mailbox_address + offsetof(Payload, map_request), request)) {
                    return -3;
                }
            }
            return 0;
        }
        if (state == CaptureState::Pending) {
            return 0;
        }
        if (state != CaptureState::Ready ||
            payload->map_result != static_cast<u32>(CaptureResult::Success) ||
            payload->map_completed == 0 ||
            payload->map_completed != payload->map_in_flight) {
            return -3;
        }

        const auto current_stage =
            Read<u64>(memory, main_base + StageRoomManagerPointerOffset);
        if (!current_stage || *current_stage != payload->map_stage) {
            Write(memory, mailbox_address + offsetof(Payload, map_acknowledged),
                  payload->map_completed);
            return 0;
        }
        if (payload->map_format != GxTextureFormatRgb5a3 &&
            payload->map_format != GxTextureFormatRgba8) {
            // Fail closed until a format has a verified GX block decoder.
            Write(memory, mailbox_address + offsetof(Payload, map_acknowledged),
                  payload->map_completed);
            return -4;
        }
        const auto source_size = MapTiledSourceSize(
            payload->map_width, payload->map_height, payload->map_format);
        if (!source_size || !payload->map_texture || !payload->map_data ||
            !IsReadableRange(memory, payload->map_data, *source_size)) {
            Write(memory, mailbox_address + offsetof(Payload, map_acknowledged),
                  payload->map_completed);
            return -5;
        }

        const std::size_t pixel_size = static_cast<std::size_t>(payload->map_width) *
                                       payload->map_height * 4;
        if (pixel_size > std::numeric_limits<std::size_t>::max() -
                             sizeof(MapImageHeaderV1)) {
            return -5;
        }
        const std::size_t required = sizeof(MapImageHeaderV1) + pixel_size;
        if (required > static_cast<std::size_t>(std::numeric_limits<int>::max())) {
            return -5;
        }
        if (output_size < required) {
            return -static_cast<int>(required);
        }

        tiled.resize(*source_size);
        if (!ReadBytes(memory, payload->map_data, tiled.data(), tiled.size())) {
            return -5;
        }
        if (!Write(memory, mailbox_address + offsetof(Payload, map_acknowledged),
                   payload->map_completed)) {
            return -3;
        }
        capture = *payload;
    }

    MapImageHeaderV1 header{};
    header.magic = MapImageMagic;
    header.version = 1;
    header.header_size = sizeof(header);
    header.sequence = capture.map_completed;
    header.width = capture.map_width;
    header.height = capture.map_height;
    header.row_stride = static_cast<u32>(capture.map_width) * 4;
    header.pixel_format = MapImagePixelFormatRgba8888;
    header.source_format = capture.map_format;
    header.floor = capture.map_floor;
    std::memcpy(header.stage_name, capture.map_stage_name.data(),
                sizeof(header.stage_name));
    std::memcpy(output, &header, sizeof(header));

    auto* pixels = static_cast<u8*>(output) + sizeof(header);
    const std::size_t blocks_x = (static_cast<std::size_t>(capture.map_width) + 3) / 4;
    for (std::size_t y = 0; y < capture.map_height; ++y) {
        for (std::size_t x = 0; x < capture.map_width; ++x) {
            const std::size_t block = (y / 4) * blocks_x + (x / 4);
            const std::size_t in_block = (y & 3U) * 8 + (x & 3U) * 2;
            const std::size_t destination =
                (y * static_cast<std::size_t>(capture.map_width) + x) * 4;
            if (capture.map_format == GxTextureFormatRgb5a3) {
                const std::size_t source = block * 32 + in_block;
                const u16 texel = static_cast<u16>(
                    (static_cast<u16>(tiled[source]) << 8) | tiled[source + 1]);
                if ((texel & 0x8000U) != 0) {
                    const u8 red = static_cast<u8>((texel >> 10) & 0x1FU);
                    const u8 green = static_cast<u8>((texel >> 5) & 0x1FU);
                    const u8 blue = static_cast<u8>(texel & 0x1FU);
                    pixels[destination + 0] = static_cast<u8>((red << 3) | (red >> 2));
                    pixels[destination + 1] =
                        static_cast<u8>((green << 3) | (green >> 2));
                    pixels[destination + 2] = static_cast<u8>((blue << 3) | (blue >> 2));
                    pixels[destination + 3] = 0xFF;
                } else {
                    const u8 alpha = static_cast<u8>((texel >> 12) & 0x07U);
                    pixels[destination + 0] =
                        static_cast<u8>(((texel >> 8) & 0x0FU) * 0x11U);
                    pixels[destination + 1] =
                        static_cast<u8>(((texel >> 4) & 0x0FU) * 0x11U);
                    pixels[destination + 2] =
                        static_cast<u8>((texel & 0x0FU) * 0x11U);
                    pixels[destination + 3] =
                        static_cast<u8>((static_cast<u16>(alpha) * 255U + 3U) / 7U);
                }
            } else {
                const std::size_t source = block * 64 + in_block;
                pixels[destination + 0] = tiled[source + 1];
                pixels[destination + 1] = tiled[source + 0x20];
                pixels[destination + 2] = tiled[source + 0x21];
                pixels[destination + 3] = tiled[source + 0];
            }
        }
    }

    return static_cast<int>(sizeof(header) +
                            static_cast<std::size_t>(capture.map_width) *
                                capture.map_height * 4);
}

bool PerformAction(EmulationSession& session, int action, int argument) {
    [[maybe_unused]] auto system_access = session.LockSystemAccess();
    if (!session.IsRunning()) {
        return false;
    }
    auto& system = session.System();
    if (system.GetApplicationProcessProgramID() != TitleId ||
        system.GetApplicationProcessBuildID() != BuildId) {
        return false;
    }
    const auto [main_base, main_size] = system.GetApplicationProcessMainModule();
    if (!main_base || main_size < RequiredMainSize) {
        return false;
    }
    auto& memory = system.ApplicationMemory();
    const VAddr file_manager =
        Read<u64>(memory, main_base + FileManagerPointerOffset).value_or(0);
    const VAddr player = Read<u64>(memory, main_base + PlayerPointerOffset).value_or(0);
    const VAddr save = file_manager ? file_manager + FileManagerSaveAOffset : 0;
    std::array<char, 8> stage{};
    const auto capacity = Read<u16>(memory, save + SaveHealthCapacityOffset);
    const auto health = Read<u16>(memory, save + SaveCurrentHealthOffset);
    std::array<s32, 8> live_pouch_items{};
    const bool pouch_read =
        ReadBytes(memory, save + SavePouchOffset, live_pouch_items.data(),
                  sizeof(live_pouch_items));
    u32 effective_capacity = capacity.value_or(0);
    if (pouch_read) {
        const auto life_medals = std::count_if(
            live_pouch_items.begin(), live_pouch_items.end(), [](s32 packed) {
                return packed >= 0 && static_cast<u8>(packed & 0xFF) == ItemLifeMedal;
            });
        effective_capacity +=
            static_cast<u32>(life_medals) * LifeMedalHealthBonus;
    }
    if (!IsReadableRange(memory, file_manager, FileManagerSaveAOffset + SaveFileSize) ||
        !IsReadableRange(memory, player, PlayerStaminaOffset + sizeof(u32)) ||
        !ReadBytes(memory, main_base + CurrentStageOffset, stage.data(), stage.size()) ||
        !HasPlayableStageName(stage.data(), stage.size()) || !capacity || !health || !pouch_read ||
        *capacity == 0 || *capacity > MaxBaseHealthCapacity ||
        effective_capacity > MaxEffectiveHealthCapacity || *health == 0 ||
        *health > effective_capacity) {
        return false;
    }

    bool applied{};
    switch (action) {
    case ActionEquipBWheel: {
        if (argument < 0 || argument >= static_cast<int>(BWheelEquippedValues.size())) {
            return false;
        }
        const VAddr item_flag_manager =
            Read<u64>(memory, main_base + ItemFlagManagerPointerOffset).value_or(0);
        const auto flags =
            ResolveFlagReader(memory, item_flag_manager, 0x40, ItemDefinitionCount);
        if (!flags) {
            return false;
        }
        const auto& ownership = BWheelOwnershipFlags[static_cast<std::size_t>(argument)];
        const bool owned = std::any_of(
            ownership.begin(), ownership.end(),
            [&](u16 flag) { return flag != MissingItemFlag && flags->Get(flag).value_or(0) != 0; });
        if (!owned) {
            return false;
        }
        const u8 equipped = BWheelEquippedValues[static_cast<std::size_t>(argument)];
        const u16 player_equipped = equipped;
        const auto previous_saved = Read<u8>(memory, save + SaveEquippedBItemOffset);
        const auto previous_player = Read<u16>(memory, player + PlayerEquippedBItemOffset);
        if (!memory.IsValidVirtualAddressRange(save + SaveEquippedBItemOffset,
                                               sizeof(equipped)) ||
            !memory.IsValidVirtualAddressRange(player + PlayerEquippedBItemOffset,
                                               sizeof(player_equipped)) ||
            !previous_saved || !previous_player) {
            return false;
        }
        if (!Write(memory, save + SaveEquippedBItemOffset, equipped)) {
            return false;
        }
        applied = Write(memory, player + PlayerEquippedBItemOffset, player_equipped);
        if (!applied) {
            Write(memory, save + SaveEquippedBItemOffset, *previous_saved);
            Write(memory, player + PlayerEquippedBItemOffset, *previous_player);
        }
        break;
    }
    case ActionSelectPouch: {
        if (argument < 0 || argument >= 8 ||
            Read<s32>(memory, save + SavePouchOffset + static_cast<VAddr>(argument) * 4)
                    .value_or(-1) < 0) {
            return false;
        }
        const u8 slot = static_cast<u8>(argument);
        applied = Write(memory, save + SaveSelectedPouchOffset, slot);
        break;
    }
    case ActionEquipShield: {
        if (argument < 0 || argument >= 8) {
            return false;
        }
        const s32 packed =
            Read<s32>(memory, save + SavePouchOffset + static_cast<VAddr>(argument) * 4)
                .value_or(-1);
        const u8 item = static_cast<u8>(packed & 0xFF);
        if (packed < 0 || item < 0x74 || item > 0x7D) {
            return false;
        }
        const u8 slot = static_cast<u8>(argument);
        // The original game does not switch shields by writing SaveA directly. Its
        // player-model update path (raw 1.0.1 main+0xAB7CCC) consumes the requested
        // pouch slot at player+0x1A2D when UPDATE_MODEL_SHIELD is set at +0x448;
        // that game-thread path then writes SaveA, rebuilds the model, and refreshes
        // the meter. Queue the same request so every in-game consumer stays in sync.
        const auto previous_slot = Read<u8>(memory, player + PlayerShieldPouchSlotOffset);
        const auto previous_flags = Read<u32>(memory, player + PlayerModelUpdateFlagsOffset);
        if (!previous_slot || !previous_flags ||
            !Write(memory, player + PlayerShieldPouchSlotOffset, slot)) {
            return false;
        }
        const u32 update_flags = *previous_flags | UpdateModelShield;
        applied = Write(memory, player + PlayerModelUpdateFlagsOffset, update_flags);
        if (!applied) {
            Write(memory, player + PlayerShieldPouchSlotOffset, *previous_slot);
        }
        break;
    }
    case ActionSelectDowsing: {
        // SaveFile stores DowsingTarget::DowsingSlot, whose exact game enum is
        // STORY_EVENT..TREASURE plus NONE (0..8). It is not a layout icon id.
        if (argument < 0 || argument > 8) {
            return false;
        }
        const u8 slot = static_cast<u8>(argument);
        applied = Write(memory, save + SaveDowsingOffset, slot);
        break;
    }
    default:
        return false;
    }
    if (applied) {
        LOG_INFO(Frontend, "[SSHD Companion] Applied action={} argument={}", action, argument);
    }
    return applied;
}


void LogRuntimeStatus(Status status, u32 checkpoint, VAddr main_base, u64 main_size,
                      VAddr file_manager, u16 capacity, u16 health) {
    const u64 signature = (static_cast<u64>(status) << 60) ^
                          (static_cast<u64>(checkpoint) << 52) ^
                          (main_base >> 12) ^ (file_manager << 1) ^
                          (static_cast<u64>(capacity) << 16) ^ health;
    if (LoggedRuntimeSignature.exchange(signature, std::memory_order_relaxed) == signature) {
        return;
    }
    LOG_INFO(Frontend,
             "[SSHD Companion] Runtime status changed: status={} checkpoint={} main={:#x} "
             "size={:#x} file_manager={:#x} capacity={} health={}",
             static_cast<u32>(status), checkpoint, main_base, main_size, file_manager, capacity,
             health);
}

template <typename T>
std::optional<T> Read(Core::Memory::Memory& memory, VAddr address) {
    if (!address || !memory.IsValidVirtualAddressRange(address, sizeof(T))) {
        return std::nullopt;
    }
    T value{};
    if (!memory.ReadBlockUnsafe(address, &value, sizeof(value))) {
        return std::nullopt;
    }
    return value;
}

template <typename T>
bool Write(Core::Memory::Memory& memory, VAddr address, const T& value) {
    return address && memory.IsValidVirtualAddressRange(address, sizeof(T)) &&
           memory.WriteBlockUnsafe(address, &value, sizeof(value));
}

bool ReadBytes(Core::Memory::Memory& memory, VAddr address, void* output, std::size_t size) {
    return address && size && memory.IsValidVirtualAddressRange(address, size) &&
           memory.ReadBlockUnsafe(address, output, size);
}

bool IsReadableRange(Core::Memory::Memory& memory, VAddr address, std::size_t size) {
    return address && size && memory.IsValidVirtualAddressRange(address, size);
}

VAddr SelectReadablePointer(Core::Memory::Memory& memory, VAddr direct, VAddr fallback,
                            std::size_t minimum_size) {
    if (IsReadableRange(memory, direct, minimum_size)) {
        return direct;
    }
    return IsReadableRange(memory, fallback, minimum_size) ? fallback : 0;
}

std::optional<std::size_t> Rgba8TiledSourceSize(u16 width, u16 height) {
    if (width == 0 || height == 0 || width > MaxMapTextureDimension ||
        height > MaxMapTextureDimension) {
        return std::nullopt;
    }
    const std::size_t blocks_x = (static_cast<std::size_t>(width) + 3) / 4;
    const std::size_t blocks_y = (static_cast<std::size_t>(height) + 3) / 4;
    if (blocks_x > std::numeric_limits<std::size_t>::max() / blocks_y ||
        blocks_x * blocks_y > std::numeric_limits<std::size_t>::max() / 64) {
        return std::nullopt;
    }
    return blocks_x * blocks_y * 64;
}

std::optional<std::size_t> Rgb5a3TiledSourceSize(u16 width, u16 height) {
    if (width == 0 || height == 0 || width > MaxMapTextureDimension ||
        height > MaxMapTextureDimension) {
        return std::nullopt;
    }
    const std::size_t blocks_x = (static_cast<std::size_t>(width) + 3) / 4;
    const std::size_t blocks_y = (static_cast<std::size_t>(height) + 3) / 4;
    if (blocks_x > std::numeric_limits<std::size_t>::max() / blocks_y ||
        blocks_x * blocks_y > std::numeric_limits<std::size_t>::max() / 32) {
        return std::nullopt;
    }
    return blocks_x * blocks_y * 32;
}

std::optional<std::size_t> MapTiledSourceSize(u16 width, u16 height, u8 format) {
    switch (format) {
    case GxTextureFormatRgb5a3:
        return Rgb5a3TiledSourceSize(width, height);
    case GxTextureFormatRgba8:
        return Rgba8TiledSourceSize(width, height);
    default:
        return std::nullopt;
    }
}

std::optional<Loader::SshdCompanionPayload::Mailbox> ReadMapCaptureMailbox(
    Core::Memory::Memory& memory, VAddr address) {
    using Payload = Loader::SshdCompanionPayload::Mailbox;
    const auto before = Read<u32>(memory, address + offsetof(Payload, map_metadata_sequence));
    if (!before || (*before & 1U) != 0) {
        return std::nullopt;
    }
    const auto payload = Read<Payload>(memory, address);
    const auto after = Read<u32>(memory, address + offsetof(Payload, map_metadata_sequence));
    if (!payload || !after || *before != *after || (*after & 1U) != 0 ||
        payload->magic != Loader::SshdCompanionPayload::Magic ||
        payload->version != Loader::SshdCompanionPayload::Version ||
        payload->size != sizeof(Payload)) {
        return std::nullopt;
    }
    return payload;
}

bool HasReadyMapImage(Core::Memory::Memory& memory, VAddr main_base, VAddr mailbox_address) {
    const auto payload = ReadMapCaptureMailbox(memory, mailbox_address);
    if (!payload || payload->map_state !=
                        static_cast<u32>(Loader::SshdCompanionPayload::MapCaptureState::Ready) ||
        payload->map_result !=
            static_cast<u32>(Loader::SshdCompanionPayload::MapCaptureResult::Success) ||
        payload->map_completed == 0 || payload->map_completed != payload->map_in_flight ||
        (payload->map_format != GxTextureFormatRgb5a3 &&
         payload->map_format != GxTextureFormatRgba8) ||
        !payload->map_stage ||
        !payload->map_texture || !payload->map_data ||
        !MapTiledSourceSize(payload->map_width, payload->map_height,
                            payload->map_format)) {
        return false;
    }
    const auto stage = Read<u64>(memory, main_base + StageRoomManagerPointerOffset);
    return stage && *stage == payload->map_stage;
}

std::optional<std::array<u16, CurrentFlagRowCount>> ReadFlagRow(
    Core::Memory::Memory& memory, VAddr flag_space) {
    const auto data = Read<u64>(memory, flag_space + FlagSpaceDataPointerOffset);
    const auto count = Read<u16>(memory, flag_space + FlagSpaceCountOffset);
    if (!data || !*data || !count || *count < CurrentFlagRowCount || *count > 4096) {
        return std::nullopt;
    }
    std::array<u16, CurrentFlagRowCount> row{};
    if (!ReadBytes(memory, *data, row.data(), sizeof(row))) {
        return std::nullopt;
    }
    return row;
}

bool IsSanePosition(const std::array<float, 3>& position) {
    return std::all_of(position.begin(), position.end(), [](float component) {
        return std::isfinite(component) && std::abs(component) <= 10'000'000.0F;
    });
}


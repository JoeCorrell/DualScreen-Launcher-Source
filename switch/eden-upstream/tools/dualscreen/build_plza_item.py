#!/usr/bin/env python3
"""Compile build-pinned native Z-A actions; output is reproducible generated code."""
import argparse
import hashlib
from pathlib import Path
import subprocess
import tempfile

p = argparse.ArgumentParser()
p.add_argument('--llvm', type=Path, required=True)
p.add_argument('--image', type=Path, required=True)
a = p.parse_args()
image = a.image.read_bytes()
if hashlib.sha256(image).hexdigest() != 'edd828195d30708899a85c927e4831687d8d1c6b98a2396ff7d18324025833e9':
    raise ValueError('Not the verified Z-A v393216 image')
source = Path(__file__).with_name('plza_item_guest.cpp')
root = source.resolve().parents[2]
with tempfile.TemporaryDirectory(prefix='plza-item-') as directory:
    work = Path(directory)
    script = work / 'link.ld'
    script.write_text('ENTRY(plza_item_guest)\nSECTIONS { . = 0; .text : { *(.text.entry) *(.text*) *(.rodata*) . = ALIGN(4); } /DISCARD/ : { *(.comment*) *(.note*) *(.eh_frame*) } }\n')
    elf = work / 'helper.elf'
    subprocess.run([str(a.llvm / 'clang++.exe'), '--target=aarch64-none-elf', '-std=c++20', '-Os',
        '-Wall', '-Wextra', '-Werror', '-ffreestanding', '-fno-strict-aliasing', '-fno-builtin',
        '-fno-exceptions', '-fno-rtti', '-fno-stack-protector', '-mno-outline-atomics',
        '-fPIC', '-nostdlib', '-fuse-ld=lld', f'-Wl,-T,{script}', str(source), '-o', str(elf)], check=True)
    subprocess.run([str(a.llvm / 'llvm-objcopy.exe'), '-O', 'binary', str(elf), str(work / 'helper.bin')], check=True)
    blob = (work / 'helper.bin').read_bytes()
    if len(blob) % 4 or len(blob) > 0x3000: raise ValueError('Bridge exceeds reservation')
    rows = [', '.join(f'0x{int.from_bytes(blob[i:i+4], "little"):08X}U'
        for i in range(start, min(start + 32, len(blob)), 4)) for start in range(0, len(blob), 32)]
    sites = [0x2bb00c, 0x2bcac8, 0x99e6b4, 0xa88620, 0x2bb7dc, 0x2bb680, 0x2bb90c,
             0x43b10, 0x4de870, 0x556ca0, 0x407900, 0x3668, 0x3678, 0x975a0,
             0xdb9c, 0x18d80, 0x5d30,
             0x8eae80, 0x5f8d2c, 0x5f8e90, 0x9beab0, 0x5534e0, 0x52d688, 0xb63b0,
             0xc31f10, 0xc31f84, 0xa5b588, 0xa5b5c8, 0xa5b548, 0xa5b608,
             0x941b80, 0xa5cb18, 0xc31ff0, 0xc32194, 0xa5b7e0, 0x18e44,
             0x941600, 0xa5bd0c, 0x2d2c78, 0xdb220, 0x72af0, 0xa5c670,
             0xa5a070, 0xbcea78, 0xa5d060, 0x986638, 0xa5c988, 0x120500, 0x696f10,
             0x86de84, 0x40919c, 0x2acd9d4, 0x2acda1c, 0x2acd858, 0x2acda64,
             0x52d5dc, 0xd88b8, 0x52d53c, 0x52d49c]
    signatures = ',\n'.join('    {0x%X, {%s}}' % (rva,
        ', '.join('0x%08XU' % int.from_bytes(image[i:i+4], 'little') for i in range(rva, rva+16, 4))) for rva in sites)
    (root / 'src/core/loader/plza_item_code.h').write_text(
        '// SPDX-License-Identifier: GPL-3.0-or-later\n// Generated by build_plza_item.py; do not edit.\n'
        f'// Source SHA256 (cpp + medicine header): {hashlib.sha256(source.read_bytes() + source.with_name("plza_medicine_guest.h").read_bytes()).hexdigest()}\n'
        '#pragma once\n#include <array>\n#include "common/common_types.h"\n'
        'namespace Loader::PlzaItemPayload {\nconstexpr u32 CodeOffset = 0x1000;\n'
        f'constexpr std::array<u32, {len(blob)//4}> Code{{{{\n    '+',\n    '.join(rows)+'\n}};\n'
        'struct Signature { u32 rva; std::array<u32,4> words; };\n'
        f'constexpr std::array<Signature,{len(sites)}> Signatures{{{{\n'+signatures+'\n}};\n}\n')
    print(f'Generated {len(blob)} bytes, {len(sites)} signatures')

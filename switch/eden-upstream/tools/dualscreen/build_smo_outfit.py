#!/usr/bin/env python3
"""Compile the bounded base-1.0.0 wardrobe bridge and pin every native call site."""
import argparse
import hashlib
from pathlib import Path
import subprocess
import tempfile

p = argparse.ArgumentParser()
p.add_argument('--llvm', type=Path, required=True)
p.add_argument('--image', type=Path, required=True)
a = p.parse_args()
image = a.image.read_bytes()
if hashlib.sha256(image).hexdigest() != 'ff81888c00d1374aef1522d6ef36169f4788de0759760aad8a2a0ed0e24fbf04':
    raise ValueError('Not the verified Odyssey base image')
source = Path(__file__).with_name('smo_outfit_guest.cpp')
root = source.resolve().parents[2]
with tempfile.TemporaryDirectory(prefix='smo-outfit-') as directory:
    work = Path(directory)
    script = work / 'link.ld'
    script.write_text('ENTRY(smo_outfit_guest)\nSECTIONS { . = 0; .text : { *(.text.entry) *(.text*) *(.rodata*) . = ALIGN(4); } /DISCARD/ : { *(.comment*) *(.note*) *(.eh_frame*) } }\n')
    elf = work / 'helper.elf'
    subprocess.run([str(a.llvm / 'clang++.exe'), '--target=aarch64-none-elf', '-std=c++20', '-Os',
        '-ffreestanding', '-fno-strict-aliasing', '-fno-builtin', '-fno-exceptions', '-fno-rtti',
        '-fno-stack-protector', '-mno-outline-atomics', '-fPIC', '-nostdlib', '-fuse-ld=lld',
        f'-Wl,-T,{script}', str(source), '-o', str(elf)], check=True)
    subprocess.run([str(a.llvm / 'llvm-objcopy.exe'), '-O', 'binary', str(elf), str(work / 'helper.bin')], check=True)
    blob = (work / 'helper.bin').read_bytes()
    if len(blob) % 4 or len(blob) > 0x3000: raise ValueError('Bridge exceeds reservation')
    rows = [', '.join(f'0x{int.from_bytes(blob[i:i+4], "little"):08X}U'
        for i in range(start, min(start + 32, len(blob)), 4)) for start in range(0, len(blob), 32)]
    sites = [0x4cd7b8, 0x4c9b30, 0x959c58, 0x421754, 0x2e35e0, 0x54c498, 0x54c4a4,
             0x52bb5c, 0x52bb90, 0x52b4ec, 0x52b530, 0x4cc73c,
             0x8ee66c, 0x8ef5bc, 0x52f83c, 0x248cc0, 0x52f6f4, 0x9a3450, 0x2e2c48]
    signatures = ',\n'.join('    {0x%X, {%s}}' % (rva,
        ', '.join('0x%08XU' % int.from_bytes(image[i:i+4], 'little') for i in range(rva, rva+16, 4)))
        for rva in sites)
    output = root / 'src/core/loader/smo_outfit_code.h'
    output.write_text('// SPDX-License-Identifier: GPL-3.0-or-later\n'
        '// Generated by tools/dualscreen/build_smo_outfit.py; do not edit.\n'
        f'// Source SHA256: {hashlib.sha256(source.read_bytes()).hexdigest()}\n'
        f'// Protocol SHA256: {hashlib.sha256((root / "src/core/loader/smo_outfit_protocol.h").read_bytes()).hexdigest()}\n'
        '#pragma once\n#include <array>\n#include "common/common_types.h"\n'
        'namespace Loader::SmoOutfitPayload {\n'
        '// Linked at page offset zero: ADRP-based constant loads require this alignment.\n'
        'constexpr u32 CodeAlignment = 0x1000U;\n'
        'constexpr u32 CodeOffset = CodeAlignment;\n'
        f'constexpr std::array<u32, {len(blob)//4}> Code{{{{\n    '+',\n    '.join(rows)+'\n}};\n'
        'struct Signature { u32 rva; std::array<u32,4> words; };\n'
        f'constexpr std::array<Signature,{len(sites)}> Signatures{{{{\n'+signatures+'\n}};\n}\n')
    print(f'Generated {len(blob)} guest bytes and {len(sites)} native signatures')

#!/usr/bin/env python3
"""Rebuild the position-independent guest map UI helper (Android NDK LLVM)."""
import argparse
import hashlib
from pathlib import Path
import subprocess
import tempfile

p = argparse.ArgumentParser()
p.add_argument('--llvm', type=Path, required=True)
a = p.parse_args()
root = Path(__file__).resolve().parents[2]
source = Path(__file__).with_name('sshd_map_ui.cpp')
with tempfile.TemporaryDirectory(prefix='sshd-map-ui-') as directory:
    work = Path(directory)
    script = work / 'link.ld'
    script.write_text('ENTRY(sshd_map_ui)\nSECTIONS { . = 0; .text : { *(.text.entry) *(.text*) *(.rodata*) } /DISCARD/ : { *(.comment*) *(.note*) *(.eh_frame*) } }\n')
    elf = work / 'helper.elf'
    subprocess.run([str(a.llvm / 'clang++.exe'), '--target=aarch64-none-elf', '-Os',
                    '-ffreestanding', '-fno-strict-aliasing', '-fno-builtin', '-fno-exceptions', '-fno-rtti',
                    '-fno-stack-protector', '-fPIC', '-nostdlib', '-fuse-ld=lld',
                    f'-Wl,-T,{script}', str(source), '-o', str(elf)], check=True)
    subprocess.run([str(a.llvm / 'llvm-objcopy.exe'), '-O', 'binary', str(elf),
                    str(work / 'helper.bin')], check=True)
    blob = (work / 'helper.bin').read_bytes()
    assert len(blob) % 4 == 0
    output = root / 'src/core/loader/sshd_map_ui_code.h'
    rows = [', '.join(f'0x{int.from_bytes(blob[i:i+4], "little"):08X}U'
                     for i in range(start, min(start + 32, len(blob)), 4))
            for start in range(0, len(blob), 32)]
    output.write_text('// SPDX-License-Identifier: GPL-3.0-or-later\n'
                      '// Generated by tools/dualscreen/build_sshd_map_ui.py; do not edit.\n'
                      f'// Source SHA256: {hashlib.sha256(source.read_bytes()).hexdigest()}\n'
                      '#pragma once\n#include <array>\n#include "common/common_types.h"\n'
                      'namespace Loader::SshdCompanionPayload {\n'
                      f'constexpr std::array<u32, {len(blob)//4}> MapUiCode{{{{\n    '
                      + ',\n    '.join(rows) + '\n}};\n}\n')
    print(f'Generated {len(blob)} bytes: {output}')
